def validate_typesense_query(query: Dict, question: str) -> Optional[Dict]:
    """
    Validates and corrects common errors in a Typesense query dictionary.
    
    Args:
        query: The Typesense query dictionary generated by the LLM
        question: The original natural language question for context
    
    Returns:
        The corrected Typesense query dictionary, or None if invalid
    """
    if not query or not isinstance(query, dict):
        return None
    
    corrected_query = query.copy()
    
    # 1. Ensure 'q' exists and is properly formatted
    if "q" not in corrected_query:
        corrected_query["q"] = "*"
    
    # 2. Validate and correct 'filter_by'
    if "filter_by" in corrected_query:
        if isinstance(corrected_query["filter_by"], list):
            # Convert list to string joined by &&
            corrected_query["filter_by"] = " && ".join(
                str(f) for f in corrected_query["filter_by"]
            )
        
        filter_by = str(corrected_query["filter_by"])
        
        # Fix common syntax errors
        filter_by = re.sub(r'(\w+)\s*=\s*([^&\|]+)', r'\1:=\2', filter_by)  # = to :=
        filter_by = re.sub(r'(\w+)::=', r'\1:=', filter_by)  # ::= to :=
        filter_by = re.sub(r':\s*=\s*', ':=', filter_by)  # Remove spaces around :=
        
        # Add quotes around string values if missing
        def add_quotes(match):
            field, op, value = match.groups()
            if not (value.startswith("'") and value.endswith("'")) and not value.isdigit():
                return f"{field}{op}'{value}'"
            return match.group(0)
        
        filter_by = re.sub(r'(\w+)(:=|>|<|>=|<=)([^&\|]+)', add_quotes, filter_by)
        corrected_query["filter_by"] = filter_by
    
    # 3. Validate 'per_page'
    if "per_page" in corrected_query:
        try:
            per_page = int(corrected_query["per_page"])
            corrected_query["per_page"] = max(1, min(250, per_page))  # Clamp to 1-250
        except (ValueError, TypeError):
            corrected_query["per_page"] = 250 if "how many" in question.lower() else 10
    
    # 4. Validate 'sort_by'
    if "sort_by" in corrected_query:
        sort_by = str(corrected_query["sort_by"])
        if not re.match(r'^\w+:(asc|desc)$', sort_by):
            # Try to fix common sort_by errors
            if ":" not in sort_by:
                if "oldest" in question.lower() or "highest" in question.lower():
                    sort_by = f"{sort_by}:desc"
                else:
                    sort_by = f"{sort_by}:asc"
            corrected_query["sort_by"] = sort_by
    
    # 5. Ensure required fields for certain question types
    if "oldest" in question.lower() or "youngest" in question.lower():
        corrected_query.update({
            "q": "*",
            "sort_by": "age:desc" if "oldest" in question.lower() else "age:asc",
            "per_page": 1
        })
    
    return corrected_query

def qwen_llm(question: str, schema: Dict, collection_name: str) -> Optional[Dict]:
    """
    Generates a Typesense query from natural language using Qwen LLM.
    
    Args:
        question: The natural language question
        schema: The Typesense collection schema
        collection_name: Name of the collection to query
    
    Returns:
        Validated Typesense query dictionary or None if generation failed
    """
    # Prepare the prompt with strict formatting instructions
    prompt = f"""<|begin_of_text|><|start_header_id|>system<|end_header_id|>
You are a Typesense query expert. Given this collection schema:

{json.dumps([coll for coll in schema if coll['name'] == collection_name], indent=2)}

Convert this question into a Typesense query:

Question: {question}

Requirements:
1. Output must be valid JSON with these possible keys:
   - q (search term, use '*' for all documents)
   - filter_by (string with valid filters)
   - sort_by (field:asc or field:desc)
   - per_page (1-250)
   - query_by (fields to search)
2. For filters:
   - Use := for equality (name:='John')
   - Use >, <, >=, <= for numbers (age:>30)
   - Combine with && or ||
3. For sorting:
   - Always specify direction (field:asc or field:desc)
4. Return ONLY the JSON object, no explanations.

Example response for "oldest users":
```json
{{
  "q": "*",
  "sort_by": "age:desc",
  "per_page": 5
}}
```<|eot_id|><|start_header_id|>assistant<|end_header_id|>
```json
"""
    
    try:
        inputs = tokenizer(prompt, return_tensors="pt", return_attention_mask=True).to(device)
        outputs = model.generate(
            **inputs,
            max_new_tokens=200,
            pad_token_id=tokenizer.eos_token_id,
            temperature=0.3,  # Lower temperature for more deterministic output
            do_sample=True
        )
        
        response = tokenizer.decode(outputs[0], skip_special_tokens=True)
        
        # Extract JSON from response
        json_str = response.split("```json")[1].split("```")[0].strip()
        query = json.loads(json_str)
        
        return validate_typesense_query(query, question)
    
    except (json.JSONDecodeError, ValueError, IndexError) as e:
        print(f"Failed to parse LLM response: {str(e)}")
        print("Raw response:", response)
        return None
    except Exception as e:
        print(f"Error generating query: {str(e)}")
        return None
# Perform search
def perform_search(collection_name, typesense_query):
    try:
        result = client.collections[collection_name].documents.search(typesense_query)
        return result
    except Exception as e:
        return {"error": str(e)}

