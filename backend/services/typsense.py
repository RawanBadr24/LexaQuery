# Load environment variables
load_dotenv()

# API Keys and Configs
TYPESENSE_API_KEY = os.getenv("TYPESENSE_API_KEY")
TYPESENSE_HOST = os.getenv("TYPESENSE_HOST")
TYPESENSE_PORT = os.getenv("TYPESENSE_PORT", "443")
TYPESENSE_PROTOCOL = os.getenv("TYPESENSE_PROTOCOL", "https")

print(f'APIKEY:{TYPESENSE_API_KEY}')
print(f'HOST:{TYPESENSE_HOST}')

# Initialize Typesense client
client = typesense.Client({
    'api_key': TYPESENSE_API_KEY,
    'nodes': [{
        'host': TYPESENSE_HOST,
        'port': TYPESENSE_PORT,
        'protocol': TYPESENSE_PROTOCOL
    }],
    'connection_timeout_seconds': 2
})

# Load Qwen3-4B model and tokenizer
device = "cuda" if torch.cuda.is_available() else "cpu"
tokenizer = AutoTokenizer.from_pretrained("unsloth/Qwen2.5-Coder-3B-Instruct-bnb-4bit")
model = AutoModelForCausalLM.from_pretrained("unsloth/Qwen2.5-Coder-3B-Instruct-bnb-4bit").to(device)

# Get current schema
def get_schema():
    try:
        collections = client.collections.retrieve()
        if not collections:
            print("⚠️ No collections exist in the Typesense cluster. Please create a collection.")
            return []
        print("Schema retrieved successfully")
        return collections
    except Exception as e:
        print(f"Error retrieving schema: {str(e)}")
        print("Possible causes: Invalid API key, incorrect host, or network issues.")
        return {"error": str(e)}

# Display available collections and prompt for selection
def select_collection():
    schema = get_schema()
    if isinstance(schema, dict) and "error" in schema:
        print("⚠️ Unable to retrieve collections.")
        return None
    
    if not schema:
        print("⚠️ No collections found.")
        return None

    print("\n📋 Available Collections:")
    for idx, collection in enumerate(schema, 1):
        print(f"{idx}. {collection['name']}")

    while True:
        try:
            choice = int(input("\nSelect a collection (enter the number): ")) - 1
            if 0 <= choice < len(schema):
                return schema[choice]['name']
            else:
                print("❌ Invalid selection. Please choose a valid number.")
        except ValueError:
            print("❌ Please enter a valid number.")

